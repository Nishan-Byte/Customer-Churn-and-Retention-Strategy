"""## 13. Revenue-at-Risk

`Expected Monthly Revenue at Risk = Σ(MonthlyCharges × P(Churn))`

This is gross exposure — the recurring revenue that's economically "in play" if nothing is done. Section 15 converts this into *recoverable* revenue after accounting for intervention effectiveness and cost.

"""

df['monthly_revenue_at_risk'] = df['MonthlyCharges'] * df['P_Churn']

total_revenue_at_risk = df['monthly_revenue_at_risk'].sum()

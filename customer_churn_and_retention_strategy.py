"""## 3. Encoding (Leakage-Safe)

Categorical variables are one-hot encoded and numeric variables are scaled, but this is done **inside a scikit-learn `Pipeline`/`ColumnTransformer`**, fit only on the training data. This is what "leakage-safe" means in practice: the test set never influences how encoding/scaling parameters are learned.

"""

# Drop identifier and raw target/leak columns from the feature set
